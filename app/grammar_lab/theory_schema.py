def ordered_theory_keys(keys, *, after=None):
    """Return all keys exactly once, keeping translations beside their example.

    Unknown fields retain their supplied order for web compatibility. Native
    callers may sort that unknown tail before calling for JSONB independence.
    """
    keys = list(keys)
    present = set(keys)
    ordered = []
    priorities = list(THEORY_CELL_ORDER)
    if after:
        priorities = list(dict.fromkeys(column for key in THEORY_CELL_ORDER for column in (key, *after.get(key, ()))))
    for key in priorities:
        if key == "example" and {"translation", "example_translation"} <= present:
            ordered.append("translation")
        if key in present:
            ordered.append(key)
        if key == "example" and "translation" in present and "translation" not in ordered:
            ordered.append("translation")
    ordered.extend(key for key in keys if key not in ordered)
    return ordered
