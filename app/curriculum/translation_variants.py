def translation_reference(english: str, russian: str) -> tuple[str, str]:
    """Repair explicitly reviewed reference defects, leaving all other pairs intact."""
    if not isinstance(english, str) or not isinstance(russian, str):
        return english, russian
    return _REFERENCE_CORRECTIONS.get(_source_key(english, russian), (english, russian))


def _lower_start(text: str) -> str:
    return text[0].lower() + text[1:] if text.split()[0] in _FUNCTION_STARTS else text


def _apply_reviewed_rule(english: str, rule: str) -> str | None:
    if rule.startswith('phrase:'):
        old = rule.removeprefix('phrase:')
        new = _PHRASE_RULES[old]
        match = re.search(r'(?<!\w)' + re.escape(old) + r'(?!\w)', english, re.I)
        if match is None:
            return None
        replacement = new[0].upper() + new[1:] if match.start() == 0 and english[0].isupper() else new
        return english[:match.start()] + replacement + english[match.end():]
    if rule == 'adjunct:initial-to-final':
        adjunct, main = english.split(', ', 1)
        return main[0].upper() + main[1:-1] + ' ' + adjunct[0].lower() + adjunct[1:] + '.'
    if rule == 'adjunct:final-to-initial':
        for adjunct in _FINAL_TIME_FRAMES:
            if english.endswith(' ' + adjunct + '.'):
                main = english[:-len(adjunct)-2]
                return adjunct[0].upper() + adjunct[1:] + ', ' + _lower_start(main) + '.'
    if rule == 'please:position':
        if english.startswith('Please '):
            main = english[7:-1]
            return main[0].upper() + main[1:] + ', please.'
        return 'Please ' + english[0].lower() + english[1:-9] + '.'
