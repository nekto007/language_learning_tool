#!/usr/bin/env python3
"""Back up Docker PostgreSQL and verify by restoring into an isolated container.

Host-only utility; requires Python 3, Docker, and access to the Docker daemon.
Never restores into the source database. No .env file is read by this script.
"""

import argparse
import contextlib
import datetime as dt
import fcntl
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import time
import uuid


ARCHIVE_NAME = re.compile(r"llt-db-\d{8}T\d{6}Z-[0-9a-f]{12}\.dump\Z")


def run(args, **kwargs):
    return subprocess.run(args, check=True, timeout=3600, **kwargs)


def digest(path):
    result = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            result.update(chunk)
    return result.hexdigest()


def check_checksum(path):
    checksum = path.with_suffix(".dump.sha256")
    expected = checksum.read_text().strip().split()
    if (len(expected) != 2 or expected[1] != path.name
            or not re.fullmatch(r"[0-9a-f]{64}", expected[0])
            or digest(path) != expected[0]):
        raise ValueError("Backup checksum does not match")


def verify_restore(path, source_container):
    # Reuse exactly the installed source image, without pulling from the network.
    image = run(["docker", "inspect", "--format", "{{.Image}}", source_container],
                capture_output=True, text=True).stdout.strip()
    if not re.fullmatch(r"sha256:[0-9a-f]{64}", image):
        raise ValueError("Cannot determine the PostgreSQL container image")
    name = "llt-db-verify-" + uuid.uuid4().hex
    container = None
    try:
        container = run([
            "docker", "create", "--pull=never", "--network", "none",
            "--name", name, "--label", "com.llt.backup-verification=true",
            "-e", "POSTGRES_HOST_AUTH_METHOD=trust",
            "-e", "POSTGRES_DB=restore_check", image,
        ], capture_output=True, text=True).stdout.strip()
        run(["docker", "start", container], stdout=subprocess.DEVNULL)
        deadline = time.monotonic() + 120
        while True:
            ready = subprocess.run([
                "docker", "exec", container, "pg_isready", "-U", "postgres",
                "-d", "restore_check",
            ], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=15)
            if ready.returncode == 0:
                # pg_isready can briefly see the entrypoint's temporary server.
                # The regular postmaster is PID 1 only after initialization ends.
                process = run(["docker", "exec", container, "cat", "/proc/1/comm"],
                              capture_output=True, text=True).stdout.strip()
                if process == "postgres":
                    break
            if time.monotonic() >= deadline:
                raise TimeoutError("Verification PostgreSQL did not become ready")
            time.sleep(1)
        with path.open("rb") as archive:
            run(["docker", "exec", "-i", container, "pg_restore",
                 "--exit-on-error", "--no-owner", "--no-privileges",
                 "-U", "postgres", "-d", "restore_check"], stdin=archive,
                stdout=subprocess.DEVNULL)
        tables = int(run([
            "docker", "exec", container, "psql", "-X", "-A", "-t",
            "-v", "ON_ERROR_STOP=1", "-U", "postgres", "-d", "restore_check",
            "-c", "SELECT count(*) FROM information_schema.tables "
            "WHERE table_schema NOT IN ('pg_catalog', 'information_schema') "
            "AND table_type = 'BASE TABLE'",
        ], capture_output=True, text=True).stdout.strip())
        if tables < 1:
            raise ValueError("Restored database contains no application tables")
        return {"postgres_image": image, "restored_tables": tables}
    finally:
        if container:
            # Remove only the disposable container we created, including its volume.
            run(["docker", "rm", "-f", "-v", container], stdout=subprocess.DEVNULL)


@contextlib.contextmanager
def lock_directory(directory):
    directory.mkdir(mode=0o700, parents=True, exist_ok=True)
    if directory.is_symlink() or directory.stat().st_uid != os.geteuid():
        raise ValueError("Backup directory must be owned by the current user and not a symlink")
    directory.chmod(0o700)
    with (directory / ".backup.lock").open("a") as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as error:
            raise RuntimeError("Another backup is already running") from error
        yield


def prune(directory, keep):
    # Only completed, verified archives generated by this tool are eligible.
    archives = sorted([
        path for path in directory.iterdir()
        if ARCHIVE_NAME.fullmatch(path.name) and not path.is_symlink()
        and path.with_suffix(".dump.sha256").is_file()
        and path.with_suffix(".dump.json").is_file()
    ], key=lambda path: path.stat().st_mtime_ns, reverse=True)
    for path in archives[keep:]:
        path.unlink()
        path.with_suffix(".dump.sha256").unlink()
        path.with_suffix(".dump.json").unlink()


def backup(directory, source_container, keep):
    if keep < 2:
        raise ValueError("Keep at least two verified backups")
    with lock_directory(directory):
        stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
        final = directory / (f"llt-db-{stamp}-{uuid.uuid4().hex[:12]}.dump")
        partial = final.with_suffix(".dump.partial")
        try:
            with partial.open("xb") as stream:
                # Credentials stay inside the running DB container. No password
                # is passed in argv, printed, or loaded from the host's shell env.
                run(["docker", "exec", source_container, "sh", "-eu", "-c",
                     'exec pg_dump -U "$POSTGRES_USER" -d "$POSTGRES_DB" '
                     '--format=custom --no-owner --no-privileges --lock-wait-timeout=60s'],
                    stdout=stream)
                stream.flush()
                os.fsync(stream.fileno())
            if partial.stat().st_size == 0:
                raise ValueError("pg_dump produced an empty archive")
            print("Dump created; verifying isolated restore...", flush=True)
            verification = verify_restore(partial, source_container)
            checksum = digest(partial)
            partial.rename(final)
            final.with_suffix(".dump.sha256").write_text(f"{checksum}  {final.name}\n")
            final.with_suffix(".dump.json").write_text(json.dumps({
                "created_at": dt.datetime.now(dt.timezone.utc).isoformat(),
                "size_bytes": final.stat().st_size,
                "restore_verified": True, **verification,
            }, indent=2) + "\n")
            prune(directory, keep)
            print(f"OK: {final} ({final.stat().st_size} bytes); "
                  f"restore verified, {verification['restored_tables']} tables", flush=True)
            return final
        finally:
            partial.unlink(missing_ok=True)


def status(directory, max_age_hours):
    archives = sorted((p for p in directory.glob("llt-db-*.dump")
                       if ARCHIVE_NAME.fullmatch(p.name)
                       and p.with_suffix(".dump.json").is_file()
                       and not p.is_symlink()), key=lambda p: p.stat().st_mtime_ns,
                      reverse=True)
    if not archives:
        raise ValueError("No completed backup found")
    latest = archives[0]
    check_checksum(latest)
    metadata = json.loads(latest.with_suffix(".dump.json").read_text())
    if metadata.get("restore_verified") is not True:
        raise ValueError("Latest backup has no successful restore verification")
    created = dt.datetime.fromisoformat(metadata["created_at"])
    age = (dt.datetime.now(dt.timezone.utc) - created).total_seconds() / 3600
    if age < 0 or age > max_age_hours:
        raise ValueError(f"Backup is stale or has an invalid date (age: {age:.1f} hours)")
    print(f"OK: {latest.name}; age {age:.1f} hours; SHA256 matches; restore verified")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["backup", "verify", "status"])
    parser.add_argument("archive", nargs="?", type=Path)
    parser.add_argument("--directory", type=Path, default=Path("/var/backups/llt-postgres"))
    parser.add_argument("--container", default="language_learning_tool_db")
    parser.add_argument("--keep", type=int, default=14)
    parser.add_argument("--max-age-hours", type=float, default=36)
    args = parser.parse_args()
    os.umask(0o077)
    try:
        if args.command == "backup":
            backup(args.directory, args.container, args.keep)
        elif args.command == "status":
            status(args.directory, args.max_age_hours)
        else:
            if args.archive is None:
                parser.error("verify requires an archive path and its .sha256 file")
            check_checksum(args.archive)
            result = verify_restore(args.archive, args.container)
            print(f"OK: isolated restore verified; {result['restored_tables']} tables")
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
